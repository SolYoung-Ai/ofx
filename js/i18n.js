  function t(key) {
    const e = UI[key];
    if (!e) return key;
    return lang === "en" ? (e.en || e.zh) : e.zh;
  }

  /** 数据文本翻译：英文模式且有对应翻译时返回英文，否则原文 */
  function tr(text) {
    if (lang !== "en" || text == null || text === "") return text;
    const hit = TEXT[String(text)];
    return hit != null ? hit : text;
  }

  function applyStatic() {
    document.documentElement.lang = lang === "en" ? "en" : "zh-CN";
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = t(el.getAttribute("data-i18n"));
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      el.placeholder = t(el.getAttribute("data-i18n-placeholder"));
    });
    document.querySelectorAll("[data-i18n-title]").forEach((el) => {
      el.title = t(el.getAttribute("data-i18n-title"));
    });
    document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
    });
    const btn = document.getElementById("lang-toggle");
    if (btn) btn.textContent = lang === "en" ? "中文" : "EN";
  }

  function setLang(l) {
    lang = l === "en" ? "en" : "zh";
    try { localStorage.setItem(KEY, lang); } catch (e) { /* ignore */ }
    applyStatic();
    if (window.OFXRouter && typeof window.OFXRouter.render === "function") {
      window.OFXRouter.render(window.OFXRouter.parse());
    }
  }

  function toggle() {
    setLang(lang === "en" ? "zh" : "en");
  }

  return { t, tr, setLang, toggle, applyStatic, get lang() { return lang; } };
